const fs = require("fs");
const path = require("path");

const PHOTO_DIR = "/photos/properties/Cotswolds UK - Soho Farm House";
const PHOTO_DIR_FS = path.join(
  process.cwd(),
  "public/photos/properties/Cotswolds UK - Soho Farm House"
);
const COVER_FILENAME = "224A8292.jpg";
const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i;
const PINNED_GALLERY_COUNT = 6;
const OUTPUT_PATH = path.join(process.cwd(), "src/data/cotswoldsPhotos.ts");

function seededShuffle(items, seed) {
  const shuffled = [...items];
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (Math.imul(31, hash) + seed.charCodeAt(i)) | 0;
  }

  for (let i = shuffled.length - 1; i > 0; i--) {
    hash = (Math.imul(1664525, hash) + 1013904223) | 0;
    const j = (hash >>> 0) % (i + 1);
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled;
}

function discoverCotswoldsPhotos() {
  if (!fs.existsSync(PHOTO_DIR_FS)) {
    console.warn(`Cotswolds photo directory not found: ${PHOTO_DIR_FS}`);
    return [];
  }

  const files = fs
    .readdirSync(PHOTO_DIR_FS)
    .filter((file) => IMAGE_EXT.test(file));

  const sortedRest = files
    .filter((file) => file !== COVER_FILENAME)
    .sort((a, b) => a.localeCompare(b));

  const pinned = [
    COVER_FILENAME,
    ...sortedRest.slice(0, PINNED_GALLERY_COUNT - 1),
  ];
  const remaining = sortedRest.slice(PINNED_GALLERY_COUNT - 1);
  const mixedRest = seededShuffle(
    remaining,
    "cotswolds-soho-farm-house-gallery"
  );

  return [...pinned, ...mixedRest].map((file) => `${PHOTO_DIR}/${file}`);
}

const photos = discoverCotswoldsPhotos();

const contents = `/** Auto-generated by scripts/generate-cotswolds-photos.js — do not edit manually. */
export const COTSWOLDS_COVER = "${PHOTO_DIR}/${COVER_FILENAME}";

export const COTSWOLDS_PHOTOS: string[] = ${JSON.stringify(photos, null, 2)};
`;

fs.writeFileSync(OUTPUT_PATH, contents, "utf8");
console.log(
  `Generated ${OUTPUT_PATH} with ${photos.length} Cotswolds photo paths.`
);
