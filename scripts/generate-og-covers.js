/**
 * Builds crawler-friendly 1200x800 JPEGs for iMessage / Google share images.
 * Run: node scripts/generate-og-covers.js
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = process.cwd();
const PUBLIC = path.join(ROOT, "public");
const OUT_DIR = path.join(PUBLIC, "og-covers");
const MAP_JSON_PATH = path.join(ROOT, "src/data/seo/ogCoverMap.json");
const MAP_TS_PATH = path.join(ROOT, "src/data/seo/ogCoverMap.ts");

const STATIC_COVERS = [
  "/photos/page-covers/properties.jpg",
  "/photos/page-covers/list-property.jpg",
  "/photos/page-covers/faq.jpg",
  "/photos/page-covers/about.jpg",
  "/photos/homepage/WhistlerVipConcierge-hero.jpg",
  "/photos/homepage/pm/cedars full res.jpg",
  "/photos/properties/2919 Heritage/Mountaintop.png",
  "/thumbnails/Four Seasons Resort and Residences Whistler_885.webp",
];

function firstImagesFromCatalog(source) {
  const covers = [];
  for (const match of source.matchAll(/images:\s*\[/g)) {
    const chunk = source.slice(match.index, match.index + 500);
    const quoted = chunk.match(/"(\/[^"]+)"/);
    if (quoted) covers.push(quoted[1]);
  }
  return covers;
}

function quotedImages(source) {
  return [...source.matchAll(/coverImage:\s*\n?\s*"(\/[^"]+)"/g)].map(
    (match) => match[1]
  );
}

function ogFilename(src) {
  const base = path
    .basename(src)
    .replace(/\.[^.]+$/, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48);
  const hash = crypto.createHash("md5").update(src).digest("hex").slice(0, 8);
  return `${base || "cover"}-${hash}.jpg`;
}

async function main() {
  const catalog = fs.readFileSync(
    path.join(ROOT, "src/data/properties/catalog.ts"),
    "utf8"
  );
  const blogs = fs.readFileSync(
    path.join(ROOT, "src/utils/blogArticles.ts"),
    "utf8"
  );
  const extras = [
    "/photos/properties/worldwide/Bedora Place/18 - 20260502 A7M4 01 A1_07454.jpg",
    "/photos/properties/Luxe 3-bed Scandinave/1-2 2221 Gondola Way 26.jpg",
    "/photos/properties/Pinnacle Ridge 23/Snowy Whistler Retreat with Gondola Views.png",
    "/photos/properties/Woodrun 2-bed/Woodrun snow 1.jpg",
  ];

  const sources = [
    ...firstImagesFromCatalog(catalog),
    ...quotedImages(blogs),
    ...STATIC_COVERS,
    ...extras,
  ];
  const unique = [...new Set(sources.filter(Boolean))];

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const map = {};

  for (const src of unique) {
    const input = path.join(PUBLIC, src.replace(/^\//, ""));
    if (!fs.existsSync(input)) {
      console.warn("skip missing", src);
      continue;
    }
    const filename = ogFilename(src);
    const output = path.join(OUT_DIR, filename);
    await sharp(input)
      .rotate()
      .resize(1200, 800, { fit: "cover", position: "centre" })
      .jpeg({ quality: 78, mozjpeg: true })
      .toFile(output);
    map[src] = `/og-covers/${filename}`;
    const size = fs.statSync(output).size;
    console.log(`${(size / 1024).toFixed(0)}kb  ${src} -> ${filename}`);
  }

  fs.mkdirSync(path.dirname(MAP_JSON_PATH), { recursive: true });
  fs.writeFileSync(MAP_JSON_PATH, `${JSON.stringify(map, null, 2)}\n`);
  const tsLines = [
    "/** Auto-generated by scripts/generate-og-covers.js. Compact share JPEGs. */\n",
    "export const OG_COVER_BY_SOURCE: Record<string, string> = {\n",
  ];
  for (const [src, dest] of Object.entries(map)) {
    tsLines.push(`  ${JSON.stringify(src)}: ${JSON.stringify(dest)},\n`);
  }
  tsLines.push("};\n");
  fs.writeFileSync(MAP_TS_PATH, tsLines.join(""));
  console.log(`wrote ${Object.keys(map).length} og covers`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
